"""
AuthSentinel — Database Models
================================
SQLAlchemy ORM models.  Uses SQLite by default; swap the URL for Postgres in production.
"""

from datetime import datetime, timezone
from sqlalchemy import (
    Column,
    Integer,
    String,
    DateTime,
    Float,
    Boolean,
    Text,
    Index,
)
from sqlalchemy.orm import DeclarativeBase


class Base(DeclarativeBase):
    pass


class AuthEvent(Base):
    """
    Parsed Windows Security Event (4624 / 4625 / …).

    NEVER stores passwords — only security-event metadata.
    """

    __tablename__ = "auth_events"

    id = Column(Integer, primary_key=True, autoincrement=True)
    event_id = Column(Integer, nullable=False, index=True)           # 4624 / 4625
    timestamp = Column(DateTime(timezone=True), nullable=False, index=True)
    username = Column(String(256), nullable=True, index=True)
    source_ip = Column(String(64), nullable=True)
    source_host = Column(String(256), nullable=True)
    target_computer = Column(String(256), nullable=True)
    logon_type = Column(Integer, nullable=True)
    logon_type_description = Column(String(64), nullable=True)
    status = Column(String(32), nullable=True)                        # SUCCESS / FAILURE
    risk_score = Column(Float, default=0.0)
    risk_level = Column(String(16), default="LOW")                   # LOW / MEDIUM / HIGH
    detection_reason = Column(Text, nullable=True)
    raw_record_id = Column(Integer, nullable=True)                   # Windows RecordNumber
    created_at = Column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
    )

    __table_args__ = (
        Index("ix_auth_events_username_timestamp", "username", "timestamp"),
        Index("ix_auth_events_source_ip_timestamp", "source_ip", "timestamp"),
        Index(
            "ix_auth_events_source_host_raw_record_id",
            "source_host",
            "raw_record_id",
        ),
    )


class Alert(Base):
    """
    Correlated detection alert generated by the Detection Engine.
    """

    __tablename__ = "alerts"

    id = Column(Integer, primary_key=True, autoincrement=True)
    alert_type = Column(String(64), nullable=False)                  # e.g. REPEATED_FAILURE
    username = Column(String(256), nullable=True, index=True)
    source_ip = Column(String(64), nullable=True)
    source_host = Column(String(256), nullable=True)
    target_computer = Column(String(256), nullable=True)
    risk_score = Column(Float, default=0.0)
    risk_level = Column(String(16), default="HIGH")
    failure_count = Column(Integer, default=0)
    time_window_seconds = Column(Integer, default=0)
    reason = Column(Text, nullable=True)
    status = Column(String(32), default="OPEN")                      # OPEN / INVESTIGATING / RESOLVED
    resolved = Column(Boolean, default=False)
    triggered_at = Column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        index=True,
    )
    created_at = Column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
    )


class Laboratory(Base):
    """
    Laboratory environment configuration for terminals.
    """

    __tablename__ = "laboratories"

    id = Column(String(64), primary_key=True)
    name = Column(String(256), nullable=False)
    description = Column(Text, nullable=True)
    location = Column(String(256), nullable=True)
    created_at = Column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
    )


class TerminalAssignment(Base):
    """
    Assignment mapping between terminal and lab.
    """

    __tablename__ = "terminal_assignments"

    terminal_id = Column(String(256), primary_key=True)
    lab_id = Column(String(64), nullable=True)
    assigned_at = Column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
    )


class Computer(Base):
    """
    Hardware and system telemetry for connected/assigned computers.
    """
    __tablename__ = "computers"

    terminal_id = Column(String(256), primary_key=True)
    computer_name = Column(String(256), nullable=True)
    hostname = Column(String(256), nullable=True)
    ip_address = Column(String(64), nullable=True)
    mac_address = Column(String(64), nullable=True)
    os_name = Column(String(128), nullable=True)
    os_version = Column(String(128), nullable=True)
    logged_in_user = Column(String(256), nullable=True)
    cpu = Column(String(256), nullable=True)
    ram = Column(String(128), nullable=True)
    manufacturer = Column(String(256), nullable=True)
    model = Column(String(256), nullable=True)
    status = Column(String(32), default="UNKNOWN")  # Online, Offline, Unknown
    last_seen = Column(DateTime(timezone=True), nullable=True)
    created_at = Column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
    )


class User(Base):
    """
    Authenticated users for TAVIX GUARD dashboard access.
    Email-based authentication with verification tokens and JWT tokens.
    """

    __tablename__ = "users"

    id = Column(Integer, primary_key=True, autoincrement=True)
    email = Column(String(256), nullable=False, unique=True, index=True)
    name = Column(String(256), nullable=True)
    role = Column(String(32), default="admin")
    is_verified = Column(Boolean, default=False)
    verification_token = Column(String(512), nullable=True)
    verification_token_expires_at = Column(DateTime(timezone=True), nullable=True)
    jwt_secret = Column(String(512), nullable=True)  # Secret key for JWT signing
    created_at = Column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        index=True,
    )
    verified_at = Column(DateTime(timezone=True), nullable=True)
    last_login_at = Column(DateTime(timezone=True), nullable=True)
    updated_at = Column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
    )


class RemoteCommand(Base):
    """
    Remote administrative actions queued for or executed on endpoints (e.g. Laptop A).
    Actions: shutdown, lock_screen.
    """
    __tablename__ = "remote_commands"

    id = Column(Integer, primary_key=True, autoincrement=True)
    terminal_id = Column(String(256), nullable=False, index=True)
    command = Column(String(64), nullable=False)   # "shutdown", "lock_screen", etc.
    alert_id = Column(Integer, nullable=True, index=True)
    status = Column(String(32), default="PENDING") # "PENDING", "SENT", "EXECUTED", "FAILED"
    payload = Column(Text, nullable=True)          # JSON parameters / reason
    result_message = Column(Text, nullable=True)
    created_at = Column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
    )
    executed_at = Column(DateTime(timezone=True), nullable=True)



