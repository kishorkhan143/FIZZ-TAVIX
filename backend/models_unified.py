def get_or_create_risk_band_defaults(session) -> None:
    """
    Create default risk bands if they don't exist.
    
    Args:
        session: SQLAlchemy session
    """
    from sqlalchemy import select
    
    bands = [
        RiskBand(
            id="normal",
            name="NORMAL",
            min_score=0,
            max_score=29,
            color="#10b981",
            description="Background noise - normal lab activity"
        ),
        RiskBand(
            id="watch",
            name="WATCH",
            min_score=30,
            max_score=59,
            color="#f59e0b",
            description="Monitor closely - suspicious patterns emerging"
        ),
        RiskBand(
            id="suspicious",
            name="SUSPICIOUS",
            min_score=60,
            max_score=79,
            color="#f97316",
            description="Incident opened - requires review"
        ),
        RiskBand(
            id="high_risk",
            name="HIGH_RISK",
            min_score=80,
            max_score=100,
            color="#ef4444",
            description="Critical attack pattern - immediate attention needed"
        ),
    ]
    
    # Check if bands exist
    stmt = select(RiskBand).limit(1)
    result = session.execute(stmt).first()
    
    if result is None:
        # Create default bands
        for band in bands:
            session.add(band)
        session.commit()


