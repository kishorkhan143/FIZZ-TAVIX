"""
AuthSentinel — Unified Database Models
=======================================

Combines original AuthEvent/Alert models with new risk scoring models:
- AuthEvent: Raw Windows Security events
- Alert: Threshold-based alerts (legacy)
- RiskContribution: Signal contributions to risk scores
- RiskSnapshot: Point-in-time entity risk scores
- Incident: Incident lifecycle management
- RiskBand: Risk categorization reference data

All models use timezone-aware UTC timestamps and proper indexing for performance.
"""

from datetime import datetime, timezone
from sqlalchemy import (
    Column,
    Integer,
    String,
    DateTime,
    Float,
    Boolean,
    Text,
    ForeignKey,
    Index,
)
from sqlalchemy.orm import DeclarativeBase


class Base(DeclarativeBase):
    """SQLAlchemy declarative base."""
    pass


# ============================================================================
# Original Models (threshold-based detection)
# ============================================================================

class AuthEvent(Base):
    """
    Parsed Windows Security Event (4624 / 4625 / …).

    NEVER stores passwords — only security-event metadata.
    Used as input for all risk scoring and detection algorithms.
    """

    __tablename__ = "auth_events"

    id = Column(Integer, primary_key=True, autoincrement=True)
    event_id = Column(Integer, nullable=False, index=True)           # 4624 / 4625
    timestamp = Column(DateTime(timezone=True), nullable=False, index=True)
    username = Column(String(256), nullable=True, index=True)
    source_ip = Column(String(64), nullable=True, index=True)
    source_host = Column(String(256), nullable=True)
    target_computer = Column(String(256), nullable=True, index=True)
    logon_type = Column(Integer, nullable=True)
    logon_type_description = Column(String(64), nullable=True)
    status = Column(String(32), nullable=True)                        # SUCCESS / FAILURE
    risk_score = Column(Float, default=0.0)
    risk_level = Column(String(16), default="LOW")                   # LOW / MEDIUM / HIGH
    detection_reason = Column(Text, nullable=True)
    raw_record_id = Column(Integer, nullable=True)                   # Windows RecordNumber
    event_hash = Column(String(16), nullable=True, unique=True)      # For dedup
    created_at = Column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
    )

    __table_args__ = (
        Index("ix_auth_events_username_timestamp", "username", "timestamp"),
        Index("ix_auth_events_source_ip_timestamp", "source_ip", "timestamp"),
        Index("ix_auth_events_target_computer_timestamp", "target_computer", "timestamp"),
        Index("ix_auth_events_status_timestamp", "status", "timestamp"),
    )

    def __repr__(self):
        return f"<AuthEvent {self.username}@{self.target_computer} {self.status} {self.timestamp}>"


class Alert(Base):
    """
    Correlated detection alert generated by threshold-based Detection Engine.
    Legacy model; kept for backward compatibility.
    """

    __tablename__ = "alerts"

    id = Column(Integer, primary_key=True, autoincrement=True)
    alert_type = Column(String(64), nullable=False)                  # e.g. REPEATED_FAILURE
    username = Column(String(256), nullable=True, index=True)
    source_ip = Column(String(64), nullable=True)
    source_host = Column(String(256), nullable=True)
    target_computer = Column(String(256), nullable=True)
    risk_score = Column(Float, default=0.0)
    risk_level = Column(String(16), default="HIGH")
    failure_count = Column(Integer, default=0)
    time_window_seconds = Column(Integer, default=0)
    reason = Column(Text, nullable=True)
    status = Column(String(32), default="OPEN")                      # OPEN / INVESTIGATING / RESOLVED
    resolved = Column(Boolean, default=False)
    triggered_at = Column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        index=True,
    )
    created_at = Column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
    )

    __table_args__ = (
        Index("ix_alert_triggered", "triggered_at"),
        Index("ix_alert_user", "username", "triggered_at"),
    )

    def __repr__(self):
        return f"<Alert {self.alert_type} {self.username} {self.triggered_at}>"


